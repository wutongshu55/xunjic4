#include "Common_headfile.h"

void All_Init(void)
{
    /* 上电默认走自动标定(菜单第 2 页显示 M1, KEY4 可切回固定值) */
    ADC_AutoCalib = Menu_CalibMode;

    /* 电感标定值默认(需实际标定后修改)
     *
     * 复合布局标定要点:
     *   横置 L/R : MAX = 正常巡航姿态下直道居中的读数(调好后 1500~2500)
     *   竖置 ML/MR: MAX = 十字/环岛交叉点处的峰值(3200~3550)
     * 两者绝对值【不要求一致】, 每路 100 代表各自的峰值。
     *
     * 这里先统一填 3550 作为占位: 与"峰值上限 3700"配套,
     * 归一化 100 对应峰值区间上沿, 饱和时不会溢出。
     */
    /* 现场实测默认标定值:
     *   外侧横置 L/R: 直道居中约 3588 (MAX 取自身满量程附近)
     *   中间竖置 ML/MR: 直道约 100(本底), 十字路口峰值约 3000
     * MIN 取直道本底, 归一化后直道 ≈0, 十字才起来。 */
    ADC_MAX[0] = 3588;  ADC_MIN[0] = 200;   /* R  右横置 */
    ADC_MAX[1] = 3000;  ADC_MIN[1] = 100;   /* MR 中右竖置(十字约 3000) */
    ADC_MAX[2] = 3000;  ADC_MIN[2] = 100;   /* ML 中左竖置(十字约 3000) */
    ADC_MAX[3] = 3588;  ADC_MIN[3] = 200;   /* L  左横置 */

    /* OLED 必须在 Timer_Init 之前初始化, 否则 TIM1 中断会打断 I2C 时序。
     * 清屏也放在开中断之前, 上电屏幕立刻亮。 */
    OLED_Init();
    OLED_Clear();
    Key_Init();
    Motor_Init();
    Encoder_Init();
    ADC_MyInit();
    Timer_Init();       /* 定时中断最后开启 */
}
